// Scans public/projects/*.txt and regenerates src/data/projects.js.
//
// Each .txt file is a plain JS object literal describing one project (see
// public/projects/_template.txt for the format, or any existing .txt for a
// real example). The slug is taken from the filename, not the file's own
// `slug` field, so it always matches the URL and the matching images folder.
//
// Also makes sure public/images/projects/<slug>/ exists for every project so
// screenshots can be dropped straight into that folder — any image files
// found there become the project's `images` array (first file = card
// thumbnail), sorted naturally (1.jpg, 2.jpg, ... 10.jpg). A folder with no
// images just falls back to the initial-letter placeholder on the site.
//
// Run automatically before `dev`/`build` (see package.json), and live while
// `npm run dev` is running (see the projectIndex plugin in vite.config.js).
// Do not hand-edit src/data/projects.js — it gets overwritten.

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const projectsDir = path.join(root, 'public', 'projects')
const imagesRoot = path.join(root, 'public', 'images', 'projects')
const outFile = path.join(root, 'src', 'data', 'projects.js')

const CATEGORIES_LINE = "export const categories = ['All', 'Frontend', 'Backend', 'Fullstack', 'Design']"
const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.svg'])

function titleCaseFromSlug(slug) {
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')
}

function parseProjectFile(text, slug) {
  try {
    // The .txt files are trusted, locally-authored object literals (same idea
    // as the blog's HTML files) — evaluating them at build time is far
    // simpler than hand-writing a JS-object parser.
    // eslint-disable-next-line no-new-func
    const factory = new Function(`"use strict"; return (\n${text}\n);`)
    return factory()
  } catch (err) {
    throw new Error(`could not parse public/projects/${slug}.txt as a JS object literal: ${err.message}`)
  }
}

function naturalSort(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' })
}

function imagesFor(slug) {
  const dir = path.join(imagesRoot, slug)
  mkdirSync(dir, { recursive: true })
  return readdirSync(dir)
    .filter((f) => IMAGE_EXTS.has(path.extname(f).toLowerCase()))
    .sort(naturalSort)
    .map((f) => `/images/projects/${slug}/${f}`)
}

function extractProject(file) {
  const slug = file.replace(/\.txt$/, '')
  const raw = readFileSync(path.join(projectsDir, file), 'utf8')
  const data = parseProjectFile(raw, slug)

  const folderImages = imagesFor(slug)
  const images = folderImages.length ? folderImages : Array.isArray(data.images) ? data.images : []

  const project = {
    slug,
    title: data.title || titleCaseFromSlug(slug),
    category: data.category || '',
    tags: Array.isArray(data.tags) ? data.tags : [],
    summary: data.summary || '',
    description: data.description || '',
    images,
    live: data.live ?? null,
    repo: data.repo ?? null,
    featured: Boolean(data.featured),
    ...(data.siteLayout ? { siteLayout: data.siteLayout } : {}),
  }

  const mtime = statSync(path.join(projectsDir, file)).mtimeMs
  return { project, mtime }
}

function jsString(str) {
  if (str.includes('\n')) {
    return '`' + str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'
  }
  return JSON.stringify(str)
}

function jsValue(value) {
  if (value === null || value === undefined) return 'null'
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    return `[${value.map((v) => jsString(String(v))).join(', ')}]`
  }
  if (typeof value === 'string') return jsString(value)
  return JSON.stringify(value)
}

function serializeProject(p) {
  const fields = Object.entries(p)
    .map(([key, value]) => `    ${key}: ${jsValue(value)},`)
    .join('\n')
  return `  {\n${fields}\n  },`
}

function run() {
  let files = []
  try {
    files = readdirSync(projectsDir).filter((f) => f.toLowerCase().endsWith('.txt') && !f.startsWith('_'))
  } catch {
    // public/projects doesn't exist yet — write an empty index instead of failing the build.
  }

  const entries = []
  for (const file of files) {
    try {
      entries.push(extractProject(file))
    } catch (err) {
      console.error(`[project-index] ${err.message}`)
    }
  }

  const projects = entries.sort((a, b) => b.mtime - a.mtime).map((e) => e.project)
  const body = projects.map(serializeProject).join('\n')

  const contents = `// AUTO-GENERATED by scripts/generate-project-index.mjs — do not hand-edit.
// Source of truth: the .txt files in public/projects/ (see the template in
// public/projects/_template.txt). Copy the template, fill it in, drop it in
// that folder, and this file regenerates on the next \`npm run dev\` /
// \`npm run build\` (or instantly while the dev server is already running).
//
// Screenshots: drop image files into public/images/projects/<slug>/ (that
// folder is created automatically for every project) — they become the
// project's \`images\` array in filename order, and the first file is used
// as the card thumbnail.

${CATEGORIES_LINE}

export const projects = [
${body}
]
`

  writeFileSync(outFile, contents)
  console.log(`[project-index] wrote ${projects.length} project(s) to src/data/projects.js`)
}

run()
